def P(name, display, arxiv, date, venue, family, chapter, one_line, key, pixel, claims,
      v1_loc=ABS, ver_loc="abs.html; PDF stamp p1"):
    return dict(name=name, display=display, arxiv=arxiv, date=date, venue=venue,
                family=family, chapter=chapter, one_line=one_line, key=key,
                pixel=pixel, claims=claims, v1_loc=v1_loc, ver_loc=ver_loc)


def C(suffix, claim, value, loc, protocol=None, note=None):
    return dict(suffix=suffix, claim=claim, value=value, loc=loc, protocol=protocol, note=note)


