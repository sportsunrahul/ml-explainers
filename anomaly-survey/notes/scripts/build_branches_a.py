def main():
    branches, claims = [], []
    for p in PAPERS:
        pre = p["name"]
        base = dict(paper=p["display"], arxiv=p["arxiv"])
        claims.append(dict(id=pre + "-published", claim=p["display"] + " arXiv v1 submission date",
                           value=p["date"], loc=p["v1_loc"], **base))
        claims.append(dict(id=pre + "-version", claim=p["display"] + " arXiv version read",
                           value=p["arxiv"], loc=p["ver_loc"], **base))
        by_suffix, by_id = {}, {}
        for c in p["claims"]:
            d = dict(id=pre + "-" + c["suffix"], claim=c["claim"], value=c["value"],
                     loc=c["loc"], **base)
            prot = c["protocol"]
            if prot and prot.startswith("same as "):
                prot = by_id[prot[len("same as "):]]["protocol"]
            if prot:
                d["protocol"] = prot
            if c["note"]:
                d["note"] = c["note"]
            claims.append(d)
            by_suffix[c["suffix"]] = d
            by_id[d["id"]] = d
        k = by_suffix[p["key"]]
        key = dict(claim_id=k["id"], label=k["claim"], value=k["value"], loc=k["loc"],
                   protocol=k.get("protocol"))
        if p["pixel"]:
            px = by_suffix[p["pixel"]]
            key["pixel_claim_id"] = px["id"]
            key["pixel_value"] = px["value"]
        assert len(p["one_line"].split()) <= 20, (pre, len(p["one_line"].split()))
        branches.append(dict(name=pre, display=p["display"], arxiv=p["arxiv"], date=p["date"],
                             venue=p["venue"], family=p["family"], parent_chapter=p["chapter"],
                             one_line=p["one_line"], key=key))

    ids = [c["id"] for c in claims]
    assert len(ids) == len(set(ids)), "duplicate claim ids"
    for name, obj in (("branches-a.json", branches), ("claims/branches-a.json", claims)):
        text = json.dumps(obj, indent=1, ensure_ascii=True) + "\n"
        assert all(ord(ch) < 128 for ch in text)
        with open(os.path.join(ROOT, "notes", name), "w", encoding="ascii") as f:
            f.write(text)
    print(len(branches), "branches,", len(claims), "claims")


