# Usage: bash build-atlas.sh [ORDER] [OUT_HTML]   ORDER lists atlas chapter ids (default atlas/ORDER).
# Assembles, in a private temp project (so parallel builds never collide): chips from each article's data-chip,
# chapters numbered "i of N" with their continue buttons, dialogs (atlas/dialogs.html + atlas/dialogs/*.html),
# scenes (shared kit + every parts/scene-*.js + atlas/scenes/<id>.js). Then builds the page and runs the atlas QA.
set -e
P=~/paper-explainers/ovd-survey; A=$P/atlas
ORDER=${1:-$A/ORDER}; OUTHTML=${2:-$P/ovd-atlas.html}
case "$ORDER" in /*) ;; *) ORDER="$P/$ORDER";; esac
case "$OUTHTML" in /*) ;; *) OUTHTML="$P/$OUTHTML";; esac
T=$(mktemp -d "${CLAUDE_JOB_DIR:-/tmp}/atlas.XXXXXX"); mkdir -p $T/atlas
python3 -I - "$ORDER" "$A" "$P" "$OUTHTML" "$T/atlas" <<'PY'
import sys,re,glob,json,os
order,A,P,out,T=sys.argv[1:6]
ids=[l.strip() for l in open(order) if l.strip()]
art={cid:open(f'{A}/chapters/{cid}.html').read() for cid in ids}
chip={cid:re.search(r'data-chip="([^"]+)"',s).group(1) for cid,s in art.items()}
cont=re.compile(r'<button type="button" class="continue" data-go="\w+">[^<]*</button>')
chips,arts=[],[]
for i,cid in enumerate(ids):
    s=re.sub(r'<span class="num">[^<]*</span>',f'<span class="num">{i+1} of {len(ids)}</span>',art[cid],1)
    if i+1<len(ids): btn=f'<button type="button" class="continue" data-go="{ids[i+1]}">Continue with {chip[ids[i+1]]}</button>'
    else: btn=f'<button type="button" class="continue" data-go="{ids[0]}">Back to the start</button>'
    arts.append(cont.sub(btn,s)); chips.append(f'      <button type="button" data-go="{cid}">{chip[cid]}</button>')
open(f'{T}/chips.html','w').write('\n'.join(chips)+'\n'); open(f'{T}/chapters.html','w').write('\n'.join(arts))
open(f'{T}/dialogs.html','w').write(open(f'{A}/dialogs.html').read()+''.join(open(f).read() for f in sorted(glob.glob(f'{A}/dialogs/*.html'))))
open(f'{T}/hero.html','w').write(open(f'{A}/hero.html').read())
strip=lambda f: '\n'.join(l for l in open(f).read().split('\n') if l.strip() not in ('<script>','</script>'))
js=['''/* Generated by build-atlas.sh: polyfills for helpers the long page has and the atlas shell lacks. */
if (!PE.mix) PE.mix = (c1, c2, u) => { const p = c => [1, 3, 5].map(i => parseInt(c.slice(i, i + 2), 16)), a = p(c1), b = p(c2); return `rgb(${a.map((v, i) => Math.round(v + (b[i] - v) * u)).join(',')})`; };
if (!PE.softmax) PE.softmax = v => { const m = Math.max(...v), e = v.map(x => Math.exp(x - m)), Z = e.reduce((s, x) => s + x, 0); return e.map(x => x / Z); };
if (!PE.linkPulses) PE.linkPulses = () => () => 0;
if (!PE.view) PE.view = (W, H, span) => { const s = H / span; return { s, X: x => W / 2 + x * s, Y: y => H / 2 - y * s, ix: px => (px - W / 2) / s, iy: py => (H / 2 - py) / s }; };''',
    strip(f'{P}/parts/lib-detkit.js')]
js+=[strip(f) for f in sorted(glob.glob(f'{P}/parts/scene-*.js'))]
js+=[open(f'{A}/scenes/{cid}.js').read() for cid in ids if os.path.exists(f'{A}/scenes/{cid}.js')]
open(f'{T}/scenes.js','w').write('\n'.join(js))
m=json.load(open(f'{A}/meta.json')); m['out']=out; json.dump(m,open(f'{T}/meta.json','w'),indent=1)
PY
cd ~/paper-explainers/.node
node ~/.claude/skills/paper-explainer/assets/atlas/build.mjs $T
SHOTS="$(dirname "$OUTHTML")/shots-$(basename "$OUTHTML" .html)"; [ "$OUTHTML" = "$P/ovd-atlas.html" ] && SHOTS=$P/build/atlas
node ~/.claude/skills/paper-explainer/assets/atlas/test.mjs "$OUTHTML" "$SHOTS"
rm -rf $T
