# Writes parts/scene-00-whendata.js from notes/data/*.json and notes/claims/glip.json, so chart numbers are
# copied, never typed. Run: python3 -I tools/gen-when-data.py (from the project root).
import json, re
P = '/Users/rahulmishra/paper-explainers/ovd-survey'
rf = json.load(open(f'{P}/notes/data/rf100vl.json'))
cats = rf['categories'] + ['All']
rows = []
for t in rf['tables']:
    if t['id'] not in ('table2-rf100vl', 'table7-rf100vl-semi-full'): continue
    for r in t['rows']:
        rows.append({'m': r['method'], 's': r['setting'], 'tab': t['loc'].split(' (')[0], 'v': [float(r[c]) for c in cats]})
owl = json.load(open(f'{P}/notes/data/odinw35-owl.json'))
pick = {('12', 'OWL-ST'): 'owl', ('15', 'OWL-ST+FT'): 'owlft', (None, 'OWL-ST/FT ens'): 'owlens'}
od = {'owl13': owl['odinw13_subset'], 'names': [d['name'] for d in owl['datasets']], 'series': {}}
for r in owl['rows']:
    k = pick.get((r['row'], r['method']))
    if k: od['series'][k] = {'label': f"{r['method']} {r['backbone']}", 'loc': f"OWLv2 Table A4, row {r['row'] or 'ens'}",
                             'v': [r['per_dataset'][n] for n in od['names']], 'mean35': r['mean35'], 'median35': r['median35'], 'mean13': r['mean13']}
gd = json.load(open(f'{P}/notes/data/odinw35-gdino.json'))
m = gd['models']['gdino-l']
od['gdinoL'] = {'label': 'Grounding DINO L', 'loc': m['loc'], 'names': gd['dataset_order'], 'v': [float(m['ap'][n]) for n in gd['dataset_order']],
                'mean35': m['printed_average'], 'median35': m['printed_median']}
g = {c['id']: c['value'] for c in json.load(open(f'{P}/notes/claims/glip.json'))}
shots = ['0shot', '1shot', '3shot', '5shot', '10shot', 'full']
gl = {}
for key, lab in [('dyhead-o365', 'DyHead-T (O365), no text'), ('t', 'GLIP-T'), ('l', 'GLIP-L')]:
    vals = []
    for s in shots:
        cid = f'glip-odinw-{key}-{s}'
        vals.append(float(g[cid]) if cid in g else None)
    gl[key] = {'label': lab, 'v': vals}
gl['loc'] = 'GLIP Table 11 (ODinW-13 average AP, full-model tuning, mean of 3 runs)'
ev = {c['id']: c['value'] for c in json.load(open(f'{P}/notes/claims/evidence.json'))}
thr = ['thrnone', 'thr04', 'thr05', 'thr06', 'thr07', 'thr08', 'thr09']
d3 = {'thr': ['none', '0.4', '0.5', '0.6', '0.7', '0.8', '0.9'], 'fppc': [float(ev[f'd3-gdino-{t}-fppc']) for t in thr],
      'map': [float(ev[f'd3-gdino-{t}-map']) for t in thr], 'loc': 'D3 (2307.12813v2): Grounding DINO base, no-instance FPPC and FULL mAP by score threshold'}
rn = [{'set': ds, 'orig': float(g[f'glip-prompt-{ds.lower()}-orig']), 'new': float(g[f'glip-prompt-{ds.lower()}-designed']), 'src': 'GLIP Table 10'}
      for ds in ['Aquarium', 'Rabbits', 'EgoHands', 'Mushrooms', 'Packages', 'Pothole']]
rn.append({'set': 'pushable-pullable', 'orig': float(ev['fsod-vlm-pushable-before']), 'new': float(ev['fsod-vlm-pushable-after']), 'src': 'FSOD-VLM Sec. 4.3'})
out = {'d3': d3, 'rename': rn, 'rf': {'cats': cats, 'rows': rows, 'loc': 'RF100-VL 2505.20612v4 Tables 2 and 7', 'industrialNames': rf['dataset_names']['values']['Industrial']},
       'odinw': od, 'glip': gl}
js = '<script>\n/* Generated by tools/gen-when-data.py from notes/data/*.json and notes/claims/glip.json. Do not edit. */\nconst WHEN_DATA = ' + json.dumps(out, separators=(',', ':')) + ';\n</script>\n'
assert all(ord(ch) < 128 for ch in js), 'non-ASCII in data'
open(f'{P}/parts/scene-00-whendata.js', 'w').write(js)
print(len(rn), 'rename rows;', d3['fppc'], d3['map']); print(len(rows), 'rf rows;', len(od['names']), 'odinw datasets;', {k: v['v'] for k, v in gl.items() if k != 'loc'})
